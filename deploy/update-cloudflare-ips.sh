#!/usr/bin/env bash
# Refresh the Cloudflare ranges nginx trusts for CF-Connecting-IP.
# Run as root, then: nginx -t && systemctl reload nginx
#
#   bash deploy/update-cloudflare-ips.sh
#
# Without these ranges the real_ip module ignores CF-Connecting-IP and every
# request looks like a Cloudflare edge IP — which breaks ADMIN_ALLOWED_IPS.
set -euo pipefail

OUT="${1:-/etc/nginx/cloudflare-ips.conf}"
TMP="$(mktemp)"

{
  echo "# Generated by deploy/update-cloudflare-ips.sh on $(date -u +%FT%TZ)"
  echo "# Sources: https://www.cloudflare.com/ips-v4 and /ips-v6"
  for url in https://www.cloudflare.com/ips-v4 https://www.cloudflare.com/ips-v6; do
    curl -fsS "$url" | sed -e 's/[[:space:]]*$//' -e '/^$/d' -e 's/^/set_real_ip_from /' -e 's/$/;/'
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

install -m 0644 "$TMP" "$OUT"
rm -f "$TMP"
echo "wrote $OUT ($(grep -c '^set_real_ip_from' "$OUT") ranges)"
